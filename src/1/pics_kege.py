"""Рисунки для дополнительных задач раздела № 1 (открытый банк КЕГЭ).

Буквы подписываются белой подложкой (bg), поэтому они читаются поверх линий:
подложка совпадает с фоном страницы в светлой и тёмной теме.

Схемы нарисованы заново по условиям задач, таблицы — по самим задачам:
«*» — дорога есть, пусто — дороги нет. Длины дорог на схемах не пишутся:
они только в таблице. Ключи — k<номер задачи в банке>.
"""
from pics import T, G


def S(cells, **kw):
    """Таблица: «*» — дорога есть, пусто — дороги нет."""
    n = len(cells)
    kw.setdefault("cols", ["П%d" % (i + 1) for i in range(n)])
    kw.setdefault("rows", [str(i + 1) for i in range(n)])
    return T(kw.pop("cols"), kw.pop("rows"), cells, **kw)


def cells_from(edges, letters, w=None):
    """Таблица по списку дорог: w(a, b) — длина, иначе «*»."""
    n = len(letters)
    cells = [[""] * n for _ in range(n)]
    for a, b in edges:
        i, j = letters.index(a), letters.index(b)
        v = "*" if w is None else str(w[frozenset((a, b))])
        cells[i][j] = v
        cells[j][i] = v
    return cells


def num_table(cells, **kw):
    """Таблица с подписями строк и столбцов П1…Пn (можно переопределить)."""
    n = len(cells)
    nums = ["П%d" % i for i in range(1, n + 1)]
    kw.setdefault("cols", nums)
    kw.setdefault("rows", list(nums))
    return S(cells, **kw)


