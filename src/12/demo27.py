def run(tape, pos, prog, state='q0', limit=10000):
    """Простой симулятор МТ: tape — dict позиция→символ, prog — {(состояние, символ): (запись, ход, новое)}.
    Возвращает ленту, позицию, состояние и список тактов."""
    trace = []
    for _ in range(limit):
        sym = tape.get(pos, 'λ'); w, mv, ns = prog[(state, sym)]
        trace.append((state, sym, w, mv, ns))
        tape[pos] = w
        if mv == 'S': return tape, pos, ns, trace
        pos += -1 if mv == 'L' else 1; state = ns
    raise RuntimeError('программа не остановилась')

def parse(spec):
    prog = {}
    for part in spec.split('|'):
        st, rest = part.split(':', 1)
        for c in rest.split(','):
            c = c.strip()
            if c:
                sym, act = c.split('>'); act = act.strip()
                prog[(st.strip(), sym.strip())] = (act[0], act[1], act[2:])
    return prog

def sub(q): return f'q<sub>{q[1:]}</sub>'

def tape_html(cells, head, q):
    """cells — символы ленты без «…» по краям; head — индекс ячейки под головкой."""
    row = '<td>…</td>' + ''.join(f'<td>{c}</td>' for c in cells) + '<td>…</td>'
    mark = '<td>&nbsp;</td>' + ''.join(f'<td>{"▲ " + sub(q) if i == head else "&nbsp;"}</td>' for i in range(len(cells))) + '<td>&nbsp;</td>'
    return f'<table><tbody><tr>{row}</tr><tr>{mark}</tr></tbody></table>'

# ---------- пример из демоверсии: Z → X ----------
ZX = 'q0: λ>λLq0, Z>XLq1 | q1: λ>λLq1, Z>XLq2 | q2: λ>λSq2, Z>XLq2'
start = list('λλZZZZλλ')
tape = {i: c for i, c in enumerate(start)}
tape, pos, q, zx_trace = run(tape, 7, parse(ZX))
end = [tape.get(i, 'λ') for i in range(len(start))]
assert ''.join(end) == 'λλXXXXλλ' and pos == 1 and q == 'q2'

def trace_html(tr):
    rows = ''.join(f'<tr><td>{i}</td><td>{sub(s)}</td><td>{c}</td><td>{w}, {m}, {sub(n)}</td></tr>' for i, (s, c, w, m, n) in enumerate(tr, 1))
    return ('<table><thead><tr><td><strong>Такт</strong></td><td><strong>Состояние</strong></td>'
            '<td><strong>Символ под головкой</strong></td><td><strong>Команда</strong></td></tr></thead>'
            f'<tbody>{rows}</tbody></table>')

